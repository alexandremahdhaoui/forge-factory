package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const (
	goHeader   = "// Generated by forge-factory. DO NOT EDIT. Source: forge-factory.yaml\n"
	crlfHeader = "// Generated by forge-factory. DO NOT EDIT. Source: forge-factory.yaml\r\n"
)

const memberGoMod = `module example.com/member

go 1.24

require example.com/single v1.0.0 // indirect

require (
	example.com/declared v1.1.0
	example.com/undeclared v2.0.0
	example.com/indirect v0.3.0 // indirect
)

replace example.com/declared => ../declared
`

func render(t *testing.T, gomod string) (string, *RenderOutput, error) {
	t.Helper()

	root := t.TempDir()
	member := filepath.Join(root, "member")
	require.NoError(t, os.MkdirAll(member, 0o750))

	if gomod != "" {
		require.NoError(t, os.WriteFile(filepath.Join(member, "go.mod"), []byte(gomod), 0o600))
	}

	out, err := NewHandlers().Render(t.Context(), RenderInput{
		Root: root,
		Repos: []Repo{{
			Name: "member", Path: member, Languages: []string{"go"},
			Identity: map[string]string{"module": "example.com/renamed", "goVersion": "1.26"},
		}},
		Dependencies: map[string]string{
			"example.com/single":   "v1.0.5",
			"example.com/declared": "v1.2.0",
			"example.com/indirect": "v0.4.0",
			"example.com/absent":   "v9.0.0",
			"example.com/quoted":   "v3.1.0",
		},
	})

	return root, out, err
}

func renderMember(t *testing.T, gomod string) (string, *RenderOutput) {
	t.Helper()

	root, out, err := render(t, gomod)
	require.NoError(t, err)

	return root, out
}

func goModOf(t *testing.T, out *RenderOutput, path string) string {
	t.Helper()

	for _, f := range out.Files {
		if f.Path == path {
			return f.Content
		}
	}

	t.Fatalf("the render wrote no %s", path)

	return ""
}

func TestTheGoEngineKeepsTheMemberGoModAndSetsOnlyTheDeclaredVersions(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, memberGoMod)

	assert.Equal(t, `// Generated by forge-factory. DO NOT EDIT. Source: forge-factory.yaml
module example.com/renamed

go 1.26

require example.com/single v1.0.5 // indirect

require (
	example.com/declared v1.2.0
	example.com/undeclared v2.0.0
	example.com/indirect v0.4.0 // indirect
)

replace example.com/declared => ../declared
`, goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineWritesOnlyTheHeaderModuleAndGoLineForAMemberWithNoGoMod(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "")

	assert.Equal(t,
		"// Generated by forge-factory. DO NOT EDIT. Source: forge-factory.yaml\n\nmodule example.com/renamed\n\ngo 1.26\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineSetsARequireWrittenWithAnySpacingOrATrailingComment(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "module example.com/member\n\ngo 1.24\n\n"+
		"require(\n\texample.com/single v1.0.0\n)\n\n"+
		"require  (\n\texample.com/declared v1.1.0\n)\n\n"+
		"require ( // grouped\n\texample.com/indirect v0.3.0 // indirect\n)\n\n"+
		"require\texample.com/absent v8.0.0\n\n"+
		"require \"example.com/quoted\" v3.0.0\n")

	assert.Equal(t, goHeader+"module example.com/renamed\n\ngo 1.26\n\n"+
		"require(\n\texample.com/single v1.0.5\n)\n\n"+
		"require  (\n\texample.com/declared v1.2.0\n)\n\n"+
		"require ( // grouped\n\texample.com/indirect v0.4.0 // indirect\n)\n\n"+
		"require\texample.com/absent v9.0.0\n\n"+
		"require \"example.com/quoted\" v3.1.0\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineRefusesARequireItCannotReadAndNamesTheFileAndTheLine(t *testing.T) {
	t.Parallel()

	root, _, err := render(t, "module example.com/member\n\ngo 1.24\n\nrequire example.com/single\n")

	require.Error(t, err)
	assert.Contains(t, err.Error(), filepath.Join(root, "member", "go.mod"))
	assert.Contains(t, err.Error(), "line 5 cannot be read: require example.com/single")
}

func TestTheGoEngineRefusesAFactoredModuleBlockAndNamesTheFileAndTheLine(t *testing.T) {
	t.Parallel()

	root, _, err := render(t, "module (\n\texample.com/old\n)\n\ngo 1.24\n")

	require.Error(t, err)
	assert.Contains(t, err.Error(), filepath.Join(root, "member", "go.mod"))
	assert.Contains(t, err.Error(), "line 1 opens a factored module block")
}

func TestTheGoEngineKeepsTheTrailingCommentOfTheModuleAndGoLines(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "// Deprecated: use other\nmodule example.com/old // Deprecated: use other\n\ngo 1.24 // pinned\n")

	assert.Equal(t,
		goHeader+"// Deprecated: use other\nmodule example.com/renamed // Deprecated: use other\n\ngo 1.26 // pinned\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineKeepsCRLFOnEveryLineIncludingTheHeaderItAdds(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "module example.com/old\r\n\r\ngo 1.24\r\n\r\nrequire example.com/single v1.0.0\r\n")

	assert.Equal(t,
		crlfHeader+"module example.com/renamed\r\n\r\ngo 1.26\r\n\r\nrequire example.com/single v1.0.5\r\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineRecognizesItsCRLFHeaderSoASecondRenderChangesNothing(t *testing.T) {
	t.Parallel()

	rendered := crlfHeader + "module example.com/renamed\r\n\r\ngo 1.26\r\n\r\nrequire example.com/single v1.0.5\r\n"

	root, out := renderMember(t, rendered)

	assert.Equal(t, rendered, goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineKeepsEveryLineOfAGodebugBlock(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "module example.com/old\n\ngo 1.24\n\ngodebug (\n\tgo 1\n\tpanicnil=1\n)\n")

	assert.Equal(t,
		goHeader+"module example.com/renamed\n\ngo 1.26\n\ngodebug (\n\tgo 1\n\tpanicnil=1\n)\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineLockSyncsTheWorkspaceBeforeItTidiesTheMember(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, memberGoMod)

	require.Len(t, out.DependencyLock, 2)
	assert.Equal(t, root, out.DependencyLock[0].Dir)
	assert.Equal(t, []string{"work", "sync"}, out.DependencyLock[0].Args)
	assert.Equal(t, filepath.Join(root, "member"), out.DependencyLock[1].Dir)
	assert.Equal(t, []string{"mod", "tidy"}, out.DependencyLock[1].Args)
	assert.Equal(t, map[string]string{"GOWORK": "off"}, out.DependencyLock[1].Env)
}
