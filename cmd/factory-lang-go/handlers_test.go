func TestTheGoEngineTakesTheGoWorkLineFromTheGoModOfAMemberThatOwnsItsManifest(t *testing.T) {
	t.Parallel()

	root, out, err := renderMembers(t,
		member{name: "owned", gomod: "module example.com/owned\n\ngo 1.27.1\n", identity: map[string]string{"manifest": "own"}},
		member{name: "rendered", identity: map[string]string{"module": "example.com/rendered", "goVersion": "1.26.5"}},
	)
	require.NoError(t, err)

	assert.Equal(t, goHeader+"\ngo 1.27.1\n\nuse (\n\t./owned\n\t./rendered\n)\n",
		goModOf(t, out, filepath.Join(root, "go.work")))
}

func TestTheGoEngineAcceptsExactlyTheDeclaredGoVersionsGoAcceptsInAGoLine(t *testing.T) {
	t.Parallel()

	for declared, accepted := range map[string]bool{
		"1":         false,
		"1.26":      true,
		"1.26.0":    true,
		"1.26rc1":   true,
		"1.26.0rc1": true,
		"tip":       false,
		" 1.26":     false,
	} {
		t.Run(declared, func(t *testing.T) {
			t.Parallel()

			root, out, err := renderIdentity(t, "", map[string]string{"module": "example.com/renamed", "goVersion": declared})

			if !accepted {
				require.Error(t, err)
				assert.Contains(t, err.Error(), fmt.Sprintf("member declares goVersion %q, which go rejects in a go line", declared))

				return
			}

			require.NoError(t, err)
			assert.Contains(t, goModOf(t, out, filepath.Join(root, "member", "go.mod")), "\ngo "+declared+"\n")
		})
	}
}

