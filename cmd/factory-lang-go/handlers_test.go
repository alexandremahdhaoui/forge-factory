func TestTheGoEngineKeepsTheTrailingCommentOfTheModuleAndGoLines(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "// Deprecated: use other\nmodule example.com/old // Deprecated: use other\n\ngo 1.24 // pinned\n")

	assert.Equal(t,
		goHeader+"// Deprecated: use other\nmodule example.com/renamed // Deprecated: use other\n\ngo 1.26 // pinned\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineKeepsCRLFOnEveryLineIncludingTheHeaderItAdds(t *testing.T) {
	t.Parallel()

	root, out := renderMember(t, "module example.com/old\r\n\r\ngo 1.24\r\n\r\nrequire example.com/single v1.0.0\r\n")

	assert.Equal(t,
		crlfHeader+"module example.com/renamed\r\n\r\ngo 1.26\r\n\r\nrequire example.com/single v1.0.5\r\n",
		goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

func TestTheGoEngineRecognizesItsCRLFHeaderSoASecondRenderChangesNothing(t *testing.T) {
	t.Parallel()

	rendered := crlfHeader + "module example.com/renamed\r\n\r\ngo 1.26\r\n\r\nrequire example.com/single v1.0.5\r\n"

	root, out := renderMember(t, rendered)

	assert.Equal(t, rendered, goModOf(t, out, filepath.Join(root, "member", "go.mod")))
}

