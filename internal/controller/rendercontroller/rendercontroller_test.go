func TestRenderingItsOwnRenderChangesNothing(t *testing.T) {
	t.Parallel()

	in := input()
	in.Dependencies = map[string]string{"sigs.k8s.io/yaml": "v1.6.0"}

	first, err := rendercontroller.NewGo(existing(t, "/w/alpha-go/go.mod", memberGoMod)).Render(in)
	require.NoError(t, err)

	rendered := find(t, first, "go.mod").Content

	second, err := rendercontroller.NewGo(existing(t, "/w/alpha-go/go.mod", rendered)).Render(in)
	require.NoError(t, err)

	assert.Equal(t, rendered, find(t, second, "go.mod").Content)
	assert.Equal(t, 1, strings.Count(rendered, goHeader))
}

