func TestGoSyncsTheWorkspaceFirstAndThenTidiesEachMember(t *testing.T) {
	t.Parallel()

	out, err := rendercontroller.NewGo(absent(t)).Render(input())
	require.NoError(t, err)
	require.Len(t, out.DependencyLock, 2)

	assert.Equal(t, "/w", out.DependencyLock[0].Dir)
	assert.Equal(t, "go", out.DependencyLock[0].Command)
	assert.Equal(t, []string{"work", "sync"}, out.DependencyLock[0].Args,
		"a go work sync raises member versions, so a tidy after it writes the sums those versions need")
	assert.Equal(t, map[string]string{"GOWORK": "/w/go.work"}, out.DependencyLock[0].Env,
		"GOWORK=off in the caller makes go work sync deny the file this sync wrote")
	assert.True(t, out.DependencyLock[0].Optional, "a sync must still work offline")

	assert.Equal(t, "/w/alpha-go", out.DependencyLock[1].Dir)
	assert.Equal(t, "go", out.DependencyLock[1].Command)
	assert.Equal(t, []string{"mod", "tidy"}, out.DependencyLock[1].Args)
	assert.Equal(t, map[string]string{"GOWORK": "off"}, out.DependencyLock[1].Env,
		"in workspace mode a tidy writes no per module sums")
	assert.True(t, out.DependencyLock[1].Optional, "a sync must still work offline")
}

